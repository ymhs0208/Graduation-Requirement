type Key = keyof typeof zh

const I18nContext = createContext<{ locale: 'zh-Hant' | 'en'; t: (key: Key) => string; setLocale: (locale: 'zh-Hant' | 'en') => void }>({
  locale: 'zh-Hant',
  t: (key) => zh[key],
  setLocale: () => undefined,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<'zh-Hant' | 'en'>('zh-Hant')
  useEffect(() => {
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-Hant-TW'
  }, [locale])
  const value = useMemo(
    () => ({
      locale,
      setLocale,
      t: (key: Key) => (locale === 'en' ? en[key] : zh[key]),
    }),
    [locale],
  )
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
